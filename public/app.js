// Check Companion Server
async function checkServerStatus() {
  try {
    const res = await fetch("/api/status", { cache: "no-store" });
    if (res.ok) {
      const data = await res.json();
      if (data.status === "ok") {
        state.hasCompanionServer = true;
        if (elements.companionText) {
          elements.companionText.textContent = "[Server Mode: Active - Live HTTPS inspection, P12 export & PQC ready]";
        }
        return;
      }
    }
  } catch (e) {}

  state.hasCompanionServer = false;
  if (elements.companionText) {
    elements.companionText.textContent = "[Browser Standalone Mode: File upload, paste, Ed25519 & samples active]";
  }
}

// Toast helper
let toastTimeout;
function showToast(msg) {
  elements.toastMsg.textContent = msg;
  elements.toast.classList.add("show");
  clearTimeout(toastTimeout);
  toastTimeout = setTimeout(() => {
    elements.toast.classList.remove("show");
  }, 2200);
}

// Tab Switching
function setupTabs() {
  const tabs = [
    { btn: elements.tabUrlBtn, panel: elements.tabUrlPanel },
    { btn: elements.tabUploadBtn, panel: elements.tabUploadPanel },
    { btn: elements.tabPasteBtn, panel: elements.tabPastePanel },
    { btn: elements.tabDemoBtn, panel: elements.tabDemoPanel }
  ];

  tabs.forEach(({ btn, panel }) => {
    btn.addEventListener("click", () => {
      tabs.forEach(t => {
        t.btn.setAttribute("aria-selected", "false");
        t.panel.classList.remove("active");
      });
      btn.setAttribute("aria-selected", "true");
      panel.classList.add("active");
    });
  });
}

// Parse Certificate and Transition to Step 2
function handleCertificateLoaded(rawInput) {
  try {
    const parsed = window.SnapInPKI.parseCertificate(rawInput);
    state.parsedCert = parsed;
    if (typeof rawInput === "string") {
      state.rawCertPem = rawInput;
    } else {
      state.rawCertPem = window.SnapInPKI.toPem(rawInput, "CERTIFICATE");
    }

    populateConfigurationForm(parsed);

    elements.stepConfig.classList.remove("hidden");
    elements.stepConfig.scrollIntoView({ behavior: "smooth", block: "start" });
    showToast("Certificate parsed successfully!");
  } catch (err) {
    console.error(err);
    alert("Error parsing certificate: " + err.message);
  }
}

// Populate Step 2 Configuration Form
function populateConfigurationForm(cert) {
  // 1. Source Metadata
  let keyDesc = "";
  if (cert.keyType === "RSA") {
    keyDesc = `RSA ${cert.keySize || 2048}-bit`;
    elements.bannerKeyType.textContent = `RSA ${cert.keySize || 2048}-bit`;
  } else if (cert.keyType === "ECDSA") {
    keyDesc = `ECDSA ${cert.ecCurve} (${cert.ecCurveAlias || "prime256v1"})`;
    elements.bannerKeyType.textContent = `ECDSA ${cert.ecCurve}`;
  } else if (cert.keyType === "ED25519") {
    keyDesc = "Ed25519 (Edwards Curve)";
    elements.bannerKeyType.textContent = "Ed25519";
  } else {
    keyDesc = cert.keyType;
    elements.bannerKeyType.textContent = cert.keyType;
  }
  elements.sourceKeySpec.textContent = keyDesc;
  elements.sourceSigSpec.textContent = `${cert.signatureAlgorithm} (${cert.signatureHash})`;

  const cn = cert.subjectMap["CN"] || "—";
  elements.sourceCN.textContent = cn;
  elements.sourceIssuer.textContent = cert.issuerSummary;
  elements.p12FriendlyName.value = cn !== "—" ? cn : "cert-bundle";

  if (cert.notBefore && cert.notAfter) {
    const fromStr = cert.notBefore.toISOString().split("T")[0];
    const toStr = cert.notAfter.toISOString().split("T")[0];
    const days = cert.daysRemaining;
    const dayLabel = days > 0 ? `(${days} days left)` : "(Expired)";
    elements.sourceValidity.textContent = `${fromStr} to ${toStr} ${dayLabel}`;
  } else {
    elements.sourceValidity.textContent = "—";
  }

  elements.sourceSerial.textContent = cert.serialHex || "—";

  if (cert.isExpired) {
    elements.sourceCertStatusBadge.style.color = "var(--highlight-err)";
    elements.sourceCertStatusBadge.textContent = "[Expired]";
  } else if (cert.daysRemaining !== null && cert.daysRemaining <= 30) {
    elements.sourceCertStatusBadge.style.color = "var(--highlight-warn)";
    elements.sourceCertStatusBadge.textContent = "[Expiring Soon]";
  } else {
    elements.sourceCertStatusBadge.style.color = "var(--highlight-match)";
    elements.sourceCertStatusBadge.textContent = "[Valid]";
  }

  // 2. Pre-populate Subject DN fields
  elements.dnCN.value = cert.subjectMap["CN"] || "";
  elements.dnO.value = cert.subjectMap["O"] || "";
  elements.dnOU.value = cert.subjectMap["OU"] || "";
  elements.dnC.value = cert.subjectMap["C"] || "";
  elements.dnST.value = cert.subjectMap["ST"] || "";
  elements.dnL.value = cert.subjectMap["L"] || "";
  elements.dnStreet.value = cert.subjectMap["STREET"] || "";
  elements.dnEmail.value = cert.subjectMap["EMAIL"] || "";

  // 3. Pre-populate SAN list
  elements.sanListContainer.innerHTML = "";
  if (cert.sanList && cert.sanList.length > 0) {
    cert.sanList.forEach(item => addSanRow(item.type, item.value));
  } else if (cn && cn !== "—") {
    addSanRow("dns", cn);
  }

  // 4. Pre-select Key Type dropdown
  let keyVal = "RSA:2048";
  if (cert.keyType === "RSA") {
    if (cert.keySize === 4096) keyVal = "RSA:4096";
    else if (cert.keySize === 3072) keyVal = "RSA:3072";
    else keyVal = "RSA:2048";
  } else if (cert.keyType === "ECDSA") {
    if (cert.ecCurve === "P-384") keyVal = "ECDSA:P-384";
    else if (cert.ecCurve === "P-521") keyVal = "ECDSA:P-521";
    else keyVal = "ECDSA:P-256";
  } else if (cert.keyType === "ED25519") {
    keyVal = "ED25519:Ed25519";
  } else if (cert.keyType === "ML-DSA-44") {
    keyVal = "MLDSA:mldsa44";
  } else if (cert.keyType === "ML-DSA-65") {
    keyVal = "MLDSA:mldsa65";
  } else if (cert.keyType === "ML-DSA-87") {
    keyVal = "MLDSA:mldsa87";
  }
  elements.keyTypeSelect.value = keyVal;

  // 5. Pre-select Hash Algorithm
  if (cert.signatureHash === "SHA-384") elements.hashSelect.value = "SHA-384";
  else if (cert.signatureHash === "SHA-512") elements.hashSelect.value = "SHA-512";
  else if (cert.keyType === "ED25519" || cert.keyType.startsWith("ML")) elements.hashSelect.value = "Ed25519";
  else elements.hashSelect.value = "SHA-256";

  // 6. Pre-select Extension check boxes
  elements.checkSAN.checked = true;
  elements.checkKeyUsage.checked = cert.hasKeyUsage;
  elements.checkEKU.checked = cert.ekuList && cert.ekuList.length > 0;
  elements.checkBasicConstraints.checked = false;

  updateCompatibilityStatus();
}

// SAN row builder
function addSanRow(type = "dns", value = "") {
  const row = document.createElement("div");
  row.className = "san-row";

  row.innerHTML = `
    <select class="san-type-select">
      <option value="dns" ${type === "dns" ? "selected" : ""}>DNS</option>
      <option value="ip" ${type === "ip" ? "selected" : ""}>IP Address</option>
      <option value="email" ${type === "email" ? "selected" : ""}>Email</option>
      <option value="uri" ${type === "uri" ? "selected" : ""}>URI</option>
    </select>
    <input type="text" class="san-value-input" value="${value}" placeholder="e.g. sub.domain.com or 192.168.1.1">
    <button type="button" class="btn-del-san" title="Remove this SAN">Remove</button>
  `;

  row.querySelector(".btn-del-san").addEventListener("click", () => {
    row.remove();
    updateCompatibilityStatus();
  });

  row.querySelector(".san-value-input").addEventListener("input", updateCompatibilityStatus);
  row.querySelector(".san-type-select").addEventListener("change", updateCompatibilityStatus);

  elements.sanListContainer.appendChild(row);
}

// Compatibility check
function updateCompatibilityStatus() {
  if (!state.parsedCert) return;

  const currentKey = elements.keyTypeSelect.value;
  let matchesKey = false;
  if (state.parsedCert.keyType === "RSA") {
    matchesKey = currentKey === `RSA:${state.parsedCert.keySize || 2048}`;
  } else if (state.parsedCert.keyType === "ECDSA") {
    matchesKey = currentKey === `ECDSA:${state.parsedCert.ecCurve || "P-256"}`;
  } else if (state.parsedCert.keyType === "ED25519") {
    matchesKey = currentKey === "ED25519:Ed25519";
  }

  if (matchesKey) {
    elements.keyMatchBadge.style.color = "var(--highlight-match)";
    elements.keyMatchBadge.textContent = "[Exact Match]";
    elements.matchBadge.textContent = "100% Match";
    elements.matchBadge.style.color = "var(--highlight-match)";
  } else {
    elements.keyMatchBadge.style.color = "var(--highlight-warn)";
    elements.keyMatchBadge.textContent = "[Customized]";
    elements.matchBadge.textContent = "Customized";
    elements.matchBadge.style.color = "var(--highlight-warn)";
  }
}

// Generate Snap-In CSR
async function handleGenerateCSR() {
  if (!elements.dnCN.value.trim()) {
    alert("Common Name (CN) is required to generate a certificate request.");
    elements.dnCN.focus();
    return;
  }

  const [selectedKeyType, keyParam] = elements.keyTypeSelect.value.split(":");
  const hashAlgorithm = elements.hashSelect.value;

  // Collect Subject attributes
  const subjectAttributes = [];
  if (elements.dnCN.value.trim()) subjectAttributes.push({ oid: "2.5.4.3", short: "CN", value: elements.dnCN.value.trim() });
  if (elements.dnO.value.trim()) subjectAttributes.push({ oid: "2.5.4.10", short: "O", value: elements.dnO.value.trim() });
  if (elements.dnOU.value.trim()) subjectAttributes.push({ oid: "2.5.4.11", short: "OU", value: elements.dnOU.value.trim() });
  if (elements.dnC.value.trim()) subjectAttributes.push({ oid: "2.5.4.6", short: "C", value: elements.dnC.value.trim().toUpperCase() });
  if (elements.dnST.value.trim()) subjectAttributes.push({ oid: "2.5.4.8", short: "ST", value: elements.dnST.value.trim() });
  if (elements.dnL.value.trim()) subjectAttributes.push({ oid: "2.5.4.7", short: "L", value: elements.dnL.value.trim() });
  if (elements.dnStreet.value.trim()) subjectAttributes.push({ oid: "2.5.4.9", short: "street", value: elements.dnStreet.value.trim() });
  if (elements.dnEmail.value.trim()) subjectAttributes.push({ oid: "1.2.840.113549.1.9.1", short: "emailAddress", value: elements.dnEmail.value.trim() });

  // Collect SANs
  const sanList = [];
  const rows = elements.sanListContainer.querySelectorAll(".san-row");
  rows.forEach(r => {
    const type = r.querySelector(".san-type-select").value;
    const value = r.querySelector(".san-value-input").value.trim();
    if (value) sanList.push({ type, value });
  });

  // Collect Key Usages
  const keyUsages = [];
  if (elements.checkKeyUsage.checked) {
    if (selectedKeyType === "RSA") {
      keyUsages.push("digitalSignature", "keyEncipherment");
    } else {
      keyUsages.push("digitalSignature", "keyAgreement");
    }
  }

  // Collect EKUs
  const ekus = [];
  if (elements.checkEKU.checked) {
    ekus.push("1.3.6.1.5.5.7.3.1"); // serverAuth
    ekus.push("1.3.6.1.5.5.7.3.2"); // clientAuth
  }

  elements.genBtnSpinner.classList.remove("hidden");
  elements.genBtnText.textContent = "Generating Cryptographic Key Pair...";
  elements.generateCsrBtn.disabled = true;

  try {
    let result;

    // Post-Quantum ML-DSA handling
    if (selectedKeyType === "MLDSA") {
      if (state.hasCompanionServer) {
        const res = await fetch("/api/generate-pqc", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ algorithm: keyParam, subjectAttributes, sanList })
        });
        const data = await res.json();
        if (!res.ok || !data.success) throw new Error(data.error || "PQC generation failed on server");
        result = {
          csrPem: data.csrPem,
          privateKeyPem: data.keyPem,
          keyType: data.keyType,
          keySize: null,
          ecCurve: null,
          hashAlgorithm: "Pure",
          extensionsCount: sanList.length
        };
      } else {
        alert("ML-DSA (Post-Quantum) key generation requires OpenSSL 4.1 via the companion server. Run 'node server.js' to enable server PQC generation. In the meantime, use the generated 'request.cnf' with OpenSSL CLI.");
        throw new Error("PQC server required for ML-DSA");
      }
    } else {
      // RSA, ECDSA, Ed25519 in client-side WebCrypto!
      result = await window.SnapInPKI.generateSnapInCSR({
        keyType: selectedKeyType,
        keySize: selectedKeyType === "RSA" ? parseInt(keyParam, 10) : null,
        ecCurve: selectedKeyType === "ECDSA" ? keyParam : (selectedKeyType === "ED25519" ? "Ed25519" : null),
        hashAlgorithm,
        subjectAttributes,
        sanList,
        includeSAN: elements.checkSAN.checked,
        includeKeyUsage: elements.checkKeyUsage.checked,
        keyUsages,
        includeEKU: elements.checkEKU.checked,
        ekus,
        includeBasicConstraints: elements.checkBasicConstraints.checked
      });
    }

    state.generatedCsr = result.csrPem;
    state.generatedKey = result.privateKeyPem;

    // Generate OpenSSL Configuration (req.cnf)
    state.generatedCnf = window.SnapInPKI.generateOpenSSLConfig({
      keyType: selectedKeyType,
      keySize: selectedKeyType === "RSA" ? parseInt(keyParam, 10) : null,
      hashAlgorithm,
      subjectAttributes,
      sanList
    });

    // Decode generated CSR to verify
    const decoded = await window.SnapInPKI.parseCSR(result.csrPem);
    state.decodedCsr = decoded;

    displayGeneratedOutput(result, decoded, selectedKeyType, keyParam);

    elements.stepOutput.classList.remove("hidden");
    elements.stepOutput.scrollIntoView({ behavior: "smooth", block: "start" });
    showToast("CSR and Private Key generated successfully!");
  } catch (err) {
    console.error("CSR generation error", err);
    if (!err.message.includes("PQC server required")) {
      alert("CSR Generation Failed: " + err.message);
    }
  } finally {
    elements.genBtnSpinner.classList.add("hidden");
    elements.genBtnText.textContent = "Generate CSR and Private Key";
    elements.generateCsrBtn.disabled = false;
  }
}

// Display Output & Verification Table
function displayGeneratedOutput(result, decoded, selectedKeyType, keyParam) {
  elements.csrPemView.textContent = result.csrPem;
  elements.keyPemView.textContent = result.privateKeyPem;
  elements.openSslCnfView.textContent = state.generatedCnf;

  // OpenSSL Verification & CLI generation commands
  let genKeyCmd = "";
  if (selectedKeyType === "RSA") genKeyCmd = `-newkey rsa:${keyParam || 2048}`;
  else if (selectedKeyType === "ECDSA") genKeyCmd = `-newkey ec -pkeyopt ec_paramgen_curve:${keyParam === "P-256" ? "prime256v1" : (keyParam === "P-384" ? "secp384r1" : "secp521r1")}`;
  else if (selectedKeyType === "ED25519") genKeyCmd = `-newkey ed25519`;
  else if (selectedKeyType === "MLDSA") genKeyCmd = `-newkey ${keyParam}`;

  const openSslCmd = `# 1. Generate equivalent CSR & Key from request.cnf via OpenSSL CLI:
openssl req -new -nodes -out request.csr -keyout private.key ${genKeyCmd} -config request.cnf

# 2. Verify CSR structure & requested extensions:
openssl req -in request.csr -text -noout

# 3. Verify self-signed cryptographic signature:
openssl req -in request.csr -verify -noout`;
  elements.openSslCmdView.textContent = openSslCmd;

  // Certbot / ACME commands
  elements.certbotCmdView.textContent = window.SnapInPKI.generateCertbotCommands("request.csr");

  // Build Comparison Table
  const original = state.parsedCert;
  const tbody = elements.comparisonTableBody;
  tbody.innerHTML = "";

  const formatKey = (type, size, curve) => {
    if (type === "RSA") return `RSA ${size || 2048}-bit`;
    if (type === "ECDSA") return `ECDSA ${curve || "P-256"}`;
    if (type === "ED25519") return "Ed25519";
    return type || "Unknown";
  };

  const origKeyStr = original ? formatKey(original.keyType, original.keySize, original.ecCurve) : "N/A";
  const genKeyStr = formatKey(decoded.keyType, decoded.keySize, decoded.ecCurve);
  const keyMatches = origKeyStr === genKeyStr;

  const origCN = original ? (original.subjectMap["CN"] || "—") : "—";
  const genCN = decoded.subjectMap["CN"] || "—";
  const cnMatches = origCN === genCN;

  const origO = original ? (original.subjectMap["O"] || "—") : "—";
  const genO = decoded.subjectMap["O"] || "—";
  const oMatches = origO === genO;

  const origC = original ? (original.subjectMap["C"] || "—") : "—";
  const genC = decoded.subjectMap["C"] || "—";
  const cMatches = origC === genC;

  const origSans = original ? ((original.sanList || []).map(s => s.value).sort().join(", ") || "None") : "None";
  const genSans = (decoded.sanList || []).map(s => s.value).sort().join(", ") || "None";
  const sanMatches = origSans === genSans;

  const rows = [
    {
      param: "Key Algorithm & Strength",
      orig: origKeyStr,
      gen: genKeyStr,
      match: keyMatches
    },
    {
      param: "Signature Algorithm Digest",
      orig: original ? original.signatureHash : "N/A",
      gen: result.hashAlgorithm,
      match: original ? (original.signatureHash === result.hashAlgorithm) : true
    },
    {
      param: "Subject Common Name (CN)",
      orig: origCN,
      gen: genCN,
      match: cnMatches
    },
    {
      param: "Subject Organization (O)",
      orig: origO,
      gen: genO,
      match: oMatches
    },
    {
      param: "Subject Country (C)",
      orig: origC,
      gen: genC,
      match: cMatches
    },
    {
      param: "Subject Alternative Names (SAN)",
      orig: origSans,
      gen: genSans,
      match: sanMatches
    },
    {
      param: "CSR Signature Self-Verification",
      orig: "N/A (Certificate)",
      gen: decoded.signatureValid ? "Valid (Self-Signature OK)" : "Invalid",
      match: decoded.signatureValid
    }
  ];

  rows.forEach(r => {
    const tr = document.createElement("tr");
    tr.innerHTML = `
      <td style="font-weight:bold;">${r.param}</td>
      <td style="font-family:monospace; font-size:11px;">${r.orig}</td>
      <td style="font-family:monospace; font-size:11px;">${r.gen}</td>
      <td class="${r.match ? "match-exact" : "match-diff"}">
        ${r.match ? "OK: Exact Match" : "Note: Value Changed"}
      </td>
    `;
    tbody.appendChild(tr);
  });
}

// Download Helper
function downloadFile(content, filename, type = "text/plain") {
  const blob = content instanceof Blob ? content : new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

// Copy to Clipboard Helper
async function copyToClipboard(text, successMsg) {
  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(text);
    } else {
      const ta = document.createElement("textarea");
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand("copy");
      document.body.removeChild(ta);
    }
    showToast(successMsg);
  } catch (e) {
    showToast("Failed to copy");
  }
}

// Event Listeners Initialization
function initEventListeners() {
  // 1. URL Fetch Form
  elements.fetchUrlBtn.addEventListener("click", async () => {
    const url = elements.urlInput.value.trim();
    if (!url) {
      elements.urlInput.focus();
      return;
    }

    elements.urlErrorAlert.classList.add("hidden");
    elements.fetchBtnSpinner.classList.remove("hidden");
    elements.fetchBtnText.textContent = "Connecting...";
    elements.fetchUrlBtn.disabled = true;

    try {
      const apiUrl = `/api/fetch-cert?url=${encodeURIComponent(url)}`;
      const res = await fetch(apiUrl);
      const data = await res.json();

      if (!res.ok || !data.success) {
        throw new Error(data.error || "Failed to fetch certificate from " + url);
      }

      handleCertificateLoaded(data.pem);
    } catch (err) {
      elements.urlErrorAlert.textContent = `TLS Error: ${err.message}. If running without local server, please use file upload, paste PEM, or sample presets.`;
      elements.urlErrorAlert.classList.remove("hidden");
    } finally {
      elements.fetchBtnSpinner.classList.add("hidden");
      elements.fetchBtnText.textContent = "Fetch Certificate";
      elements.fetchUrlBtn.disabled = false;
    }
  });

  // 2. File Upload & Drag and drop
  elements.fileInput.addEventListener("change", (e) => {
    const file = e.target.files[0];
    if (file) readFile(file);
  });

  elements.dropZone.addEventListener("dragover", (e) => {
    e.preventDefault();
  });

  elements.dropZone.addEventListener("drop", (e) => {
    e.preventDefault();
    const file = e.dataTransfer.files[0];
    if (file) readFile(file);
  });

  function readFile(file) {
    const reader = new FileReader();
    reader.onload = (e) => {
      const buffer = e.target.result;
      const u8 = new Uint8Array(buffer);
      const ascii = String.fromCharCode(...u8.slice(0, 50));
      if (ascii.includes("-----BEGIN")) {
        const text = new TextDecoder().decode(buffer);
        handleCertificateLoaded(text);
      } else {
        handleCertificateLoaded(buffer);
      }
    };
    reader.readAsArrayBuffer(file);
  }

  // 3. Paste PEM Button
  elements.parsePemBtn.addEventListener("click", () => {
    const pem = elements.pemTextarea.value.trim();
    if (!pem) {
      alert("Please paste a certificate PEM first.");
      elements.pemTextarea.focus();
      return;
    }
    handleCertificateLoaded(pem);
  });

  // 4. Sample Presets Buttons
  elements.loadSampleRsaBtn.addEventListener("click", () => {
    elements.pemTextarea.value = SAMPLE_RSA_CERT;
    handleCertificateLoaded(SAMPLE_RSA_CERT);
  });

  elements.loadSampleEcBtn.addEventListener("click", () => {
    elements.pemTextarea.value = SAMPLE_EC_CERT;
    handleCertificateLoaded(SAMPLE_EC_CERT);
  });

  elements.loadSampleEdBtn.addEventListener("click", () => {
    elements.pemTextarea.value = SAMPLE_ED_CERT;
    handleCertificateLoaded(SAMPLE_ED_CERT);
  });

  // 5. SAN actions
  elements.addSanBtn.addEventListener("click", () => {
    addSanRow("dns", "");
  });

  elements.syncCnSanBtn.addEventListener("click", () => {
    const cn = elements.dnCN.value.trim();
    if (!cn) return;

    const rows = elements.sanListContainer.querySelectorAll(".san-row");
    let found = false;
    rows.forEach(r => {
      const val = r.querySelector(".san-value-input").value.trim();
      if (val.toLowerCase() === cn.toLowerCase()) found = true;
    });

    if (!found) {
      addSanRow("dns", cn);
      showToast(`Added ${cn} to SAN`);
    } else {
      showToast(`${cn} is already present in SAN`);
    }
  });

  // 6. Form changes
  elements.keyTypeSelect.addEventListener("change", updateCompatibilityStatus);
  elements.hashSelect.addEventListener("change", updateCompatibilityStatus);
  elements.dnCN.addEventListener("input", updateCompatibilityStatus);

  // 7. Generate CSR Button
  elements.generateCsrBtn.addEventListener("click", handleGenerateCSR);

  // 8. Output action buttons
  elements.copyCsrBtn.addEventListener("click", () => {
    if (state.generatedCsr) copyToClipboard(state.generatedCsr, "CSR copied!");
  });

  elements.downloadCsrBtn.addEventListener("click", () => {
    if (state.generatedCsr) {
      const cn = elements.dnCN.value.trim().replace(/[^a-zA-Z0-9_-]/g, "_") || "request";
      downloadFile(state.generatedCsr, `${cn}.csr`, "application/x-pem-file");
    }
  });

  elements.copyKeyBtn.addEventListener("click", () => {
    if (state.generatedKey) copyToClipboard(state.generatedKey, "Private key copied!");
  });

  elements.downloadKeyBtn.addEventListener("click", () => {
    if (state.generatedKey) {
      const cn = elements.dnCN.value.trim().replace(/[^a-zA-Z0-9_-]/g, "_") || "private";
      downloadFile(state.generatedKey, `${cn}.key`, "application/x-pem-file");
    }
  });

  elements.downloadBothBtn.addEventListener("click", () => {
    if (state.generatedCsr && state.generatedKey) {
      const cn = elements.dnCN.value.trim().replace(/[^a-zA-Z0-9_-]/g, "_") || "cert_bundle";
      downloadFile(state.generatedCsr, `${cn}.csr`, "application/x-pem-file");
      setTimeout(() => {
        downloadFile(state.generatedKey, `${cn}.key`, "application/x-pem-file");
      }, 250);
      showToast("Downloaded .csr and .key");
    }
  });

  elements.copyCmdBtn.addEventListener("click", () => {
    copyToClipboard(elements.openSslCmdView.textContent, "Commands copied!");
  });

  // Item 1: Config Buttons
  elements.copyCnfBtn.addEventListener("click", () => {
    if (state.generatedCnf) copyToClipboard(state.generatedCnf, "request.cnf copied!");
  });

  elements.downloadCnfBtn.addEventListener("click", () => {
    if (state.generatedCnf) {
      downloadFile(state.generatedCnf, "request.cnf", "text/plain");
    }
  });

  // Item 6: Certbot Command Button
  elements.copyCertbotCmdBtn.addEventListener("click", () => {
    copyToClipboard(elements.certbotCmdView.textContent, "Certbot command copied!");
  });

  // Item 2: PKCS#12 Export Button
  elements.downloadP12Btn.addEventListener("click", async () => {
    if (!state.generatedKey) {
      alert("Please generate a CSR and key pair first.");
      return;
    }

    const password = elements.p12Password.value;
    const friendlyName = elements.p12FriendlyName.value.trim() || "certificate";
    const certPem = state.rawCertPem || SAMPLE_RSA_CERT;

    // Check if companion server is active
    if (state.hasCompanionServer) {
      try {
        const res = await fetch("/api/export-p12", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            keyPem: state.generatedKey,
            certPem: certPem,
            password: password,
            friendlyName: friendlyName
          })
        });

        if (!res.ok) {
          const errData = await res.json().catch(() => ({}));
          throw new Error(errData.error || "Server failed to create PKCS#12 bundle");
        }

        const blob = await res.blob();
        downloadFile(blob, `${friendlyName}.p12`, "application/x-pkcs12");
        showToast("PKCS#12 (.p12) bundle downloaded successfully!");
        return;
      } catch (err) {
        console.warn("Server P12 export failed, falling back to client-side:", err);
      }
    }

    // Client-side fallback via node-forge
    try {
      const p12Buffer = window.SnapInPKI.exportPKCS12Client(state.generatedKey, certPem, password, friendlyName);
      downloadFile(new Blob([p12Buffer], { type: "application/x-pkcs12" }), `${friendlyName}.p12`, "application/x-pkcs12");
      showToast("PKCS#12 bundle exported client-side!");
    } catch (err) {
      alert("Client PKCS#12 export error: " + err.message + "\n\nTip: You can use the OpenSSL CLI command:\nopenssl pkcs12 -export -out bundle.p12 -inkey private.key -in cert.crt -passout pass:" + password);
    }
  });
}

